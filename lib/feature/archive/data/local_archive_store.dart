import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;
import 'package:chat_archiver/feature/archive/domain/repositories/archive_file_store.dart';

/// [ArchiveFileStore] over `<root>/archives/<groupId>/...` where `<root>` is
/// the app documents directory (a temp directory in tests).
class LocalArchiveStore implements ArchiveFileStore {
  static const String archiveFile = 'archive.txt';
  static const String heldSnapshotFile = 'held_snapshot.txt';

  final Directory root;

  LocalArchiveStore(this.root);

  Directory _groupDir(String groupId) =>
      Directory(p.join(root.path, 'archives', _safe(groupId)));

  /// Group ids are generated by the app, but never trust them as a path.
  static String _safe(String id) =>
      id.replaceAll(RegExp(r'[^A-Za-z0-9_\-]'), '_');

  File _file(String groupId, String name) =>
      File(p.join(_groupDir(groupId).path, name));

  Future<String?> _read(File f) async {
    if (!await f.exists()) return null;
    return utf8.decode(await f.readAsBytes(), allowMalformed: true);
  }

  /// Temp file + rename so a crash never leaves a half-written archive.
  Future<void> _writeAtomic(File target, String text) async {
    await target.parent.create(recursive: true);
    final tmp = File('${target.path}.tmp');
    await tmp.writeAsBytes(utf8.encode(text), flush: true);
    await tmp.rename(target.path);
  }

  @override
  Future<String?> readArchive(String groupId) =>
      _read(_file(groupId, archiveFile));

  @override
  Future<void> writeArchive(String groupId, String text) =>
      _writeAtomic(_file(groupId, archiveFile), text);

  @override
  Future<String?> readHeldSnapshot(String groupId) =>
      _read(_file(groupId, heldSnapshotFile));

  @override
  Future<void> writeHeldSnapshot(String groupId, String text) =>
      _writeAtomic(_file(groupId, heldSnapshotFile), text);

  @override
  Future<void> deleteHeldSnapshot(String groupId) async {
    final f = _file(groupId, heldSnapshotFile);
    if (await f.exists()) await f.delete();
  }

  @override
  Future<List<int>> readExportBytes(String path) async {
    final f = File(path);
    if (!await f.exists()) throw ExportFileMissingException(path);
    return f.readAsBytes();
  }
}
